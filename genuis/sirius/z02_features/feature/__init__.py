def compute_batch(
    df_lazy: pl.LazyFrame,
    names: Iterable[str] | None = None,
    params: Mapping[str, Mapping[str, object]] | None = None,
) -> pl.LazyFrame:
    """批量计算因子；未指定 names 时计算全部通用因子。"""
    selected = tuple(COMMON_FACTORS) if names is None else tuple(names)
    return compute_factor_batch(
        df_lazy,
        FACTORS,
        names=selected,
        params=params,
    )


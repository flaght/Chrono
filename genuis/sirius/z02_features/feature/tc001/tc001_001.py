"""
因子代号: tc001_001
原历史名: tc001_001
因子定义: 加速度动量 γ = 对过去20周期价格拟合 Pt = α + βt + γt² 的二次项系数
"""
import polars as pl


def calculate(df_lazy: pl.LazyFrame) -> pl.LazyFrame:
    """
    计算加速度动量因子

    参数:
        df_lazy: pl.LazyFrame，必须包含 trade_time、code、close
    返回:
        pl.LazyFrame: 包含 trade_time, code, tc001_001 列
    """

    # 计算步骤:
    # 1. 生成20个滞后收盘价
    # 2. 用最小二乘法拟合 Pt = α + βt + γt²
    #    其中 t = 0, 1, ..., 19
    #    γ = [n*Σ(t²*Pt) - Σ(t²)*Σ(Pt)] / [n*Σ(t⁴) - (Σ(t²))²] 简化形式
    #    使用多元回归的正规方程求解
    # 3. 使用 .over('code') 按品种分组

    # 预计算时间常数列
    # t = 0..19, n=20
    # Σt = 190, Σt² = 2470, Σt³ = 24700, Σt⁴ = 247000 (近似)
    # 实际需要精确计算

    # 生成20个滞后价格列
    lag_cols = [f'p_{i}' for i in range(20)]

    factor_lazy = (
        df_lazy
        .sort(by=['trade_time', 'code'])
        .with_columns(
            # 生成20个滞后收盘价
            [pl.col('close').shift(i).over('code').alias(f'p_{i}') for i in range(20)]
        )
        .with_columns(
            # 计算 ΣPt（价格之和）
            sum([pl.col(f'p_{i}') for i in range(20)]).alias('sum_p'),
            # 计算 Σ(t*Pt)，t = 0..19
            sum([(i) * pl.col(f'p_{i}') for i in range(20)]).alias('sum_tp'),
            # 计算 Σ(t²*Pt)
            sum([(i**2) * pl.col(f'p_{i}') for i in range(20)]).alias('sum_t2p'),
        )
        .with_columns(
            # 使用正规方程求解 γ（二次项系数）
            # 对于 Pt = α + βt + γt² 的OLS回归
            # 令 n=20, S0=n=20, S1=Σt, S2=Σt², S3=Σt³, S4=Σt⁴
            # 通过Cramer法则求解γ
            # 简化: 使用去中心化时间变量 u = t - mean(t) 简化计算
            # mean(t) = 9.5
            # 使用 u = t - 9.5, 则 Σu = 0
            # γ = [Σ(u²)*Σ(u²*P) - Σ(u)*Σ(u*P)] / [Σ(u⁴)*Σ(u²) - (Σ(u³))²]
            # 由于 Σu = 0: γ = Σ(u²*P) / Σ(u⁴) ... 不对，需要完整公式
            # 简化方法：直接计算
            # S1 = sum(t) = 190
            # S2 = sum(t^2) = 2470
            # S3 = sum(t^3) = 24700 (不对，需要精确)
            # 精确值:
            # S1 = 0+1+...+19 = 190
            # S2 = 0+1+4+...+361 = 2470
            # S3 = 0+1+8+...+6859 = 106400 - 不对
            # 让我用公式: Σ(k=0 to n-1) k = n(n-1)/2 = 20*19/2 = 190
            # Σk² = n(n-1)(2n-1)/6 = 20*19*39/6 = 2470
            # Σk³ = [n(n-1)/2]² = 190² = 36100
            # Σk⁴ = n(n-1)(2n-1)(3n²-3n-1)/30 = 20*19*39*(3*400-60-1)/30
            #       = 20*19*39*1079/30 = 20*19*39*1079/30
            # 用另一种方式: 直接通过去中心化简化
            # 使用 u = t - 9.5
            # Σu = 0
            # Σu² = Σ(t-9.5)² = Σt² - 2*9.5*Σt + 20*9.5² = 2470 - 3610 + 1805 = 665
            # Σu³ = Σ(t-9.5)³ = ... 由于对称性 = 0
            # Σu⁴ = Σ(t-9.5)⁴
            # 对于 u = -9.5, -8.5, ..., -0.5, 0.5, ..., 8.5, 9.5
            # u⁴ = 9.5⁴ + 8.5⁴ + ... + 0.5⁴ + 0.5⁴ + ... + 8.5⁴ + 9.5⁴
            #    = 2 * (0.5⁴ + 1.5⁴ + 2.5⁴ + 3.5⁴ + 4.5⁴ + 5.5⁴ + 6.5⁴ + 7.5⁴ + 8.5⁴ + 9.5⁴)
            #    = 2 * (0.0625 + 5.0625 + 39.0625 + 150.0625 + 410.0625 + 915.0625 + 1785.0625 + 3164.0625 + 5220.0625 + 8145.0625)
            #    = 2 * 19833.5 = 39667
            # 对于 P = α + βu + γu² 的OLS（Σu=0, Σu³=0）:
            # γ = [Σu⁴ * Σ(u²P) - Σu³ * Σ(uP)] / [Σu⁴ * Σu² - (Σu³)²]
            #   = Σ(u²P) / Σu²   (因为 Σu³=0)
            #   不对，需要更仔细推导
            # 正规方程 (X'X)β = X'y
            # X = [1, u, u²], β = [α, β, γ]'
            # X'X = [[n, Σu, Σu²], [Σu, Σu², Σu³], [Σu², Σu³, Σu⁴]]
            #     = [[20, 0, 665], [0, 665, 0], [665, 0, 39667]]
            # X'y = [ΣP, ΣuP, Σu²P]
            # 从第二行: 665*β = ΣuP => β = ΣuP/665
            # 从第一行和第三行:
            # 20*α + 665*γ = ΣP
            # 665*α + 39667*γ = Σu²P
            # 解: α = (ΣP - 665*γ)/20
            # 665*(ΣP - 665*γ)/20 + 39667*γ = Σu²P
            # 665*ΣP/20 - 665²*γ/20 + 39667*γ = Σu²P
            # γ*(39667 - 665²/20) = Σu²P - 665*ΣP/20
            # γ*(39667 - 22111.25) = Σu²P - 33.25*ΣP
            # γ*17555.75 = Σu²P - 33.25*ΣP
            # γ = (Σu²P - 33.25*ΣP) / 17555.75

            # 计算 Σ(u²*P) = Σ((t-9.5)²*P_t)
            sum([(i - 9.5)**2 * pl.col(f'p_{i}') for i in range(20)]).alias('sum_u2p'),
        )
        .with_columns(
            # γ = (Σu²P - 33.25*ΣP) / 17555.75
            # 其中 33.25 = Σu²/n = 665/20
            # 17555.75 = Σu⁴ - (Σu²)²/n = 39667 - 665²/20
            ((pl.col('sum_u2p') - 33.25 * pl.col('sum_p')) / 17555.75).alias("tc001_001")
        )
        .select(['trade_time', 'code', "tc001_001"])
    )

    return factor_lazy


def compute(df_lazy: pl.LazyFrame) -> pl.LazyFrame:
    """使用默认配置构造因子计算图。"""
    return calculate(df_lazy)

# 数据频率类型：'minute' 或 'hour'
DATA_FREQUENCY = 'minute'  # 分钟数据

# 预测周期（分钟）：用于计算年化Sharpe Ratio
# 注意：nxt1_ret_15h 中的 "15h" 表示15期（periods），不是15小时
# 对于分钟数据，15期 = 15分钟
PREDICTION_PERIOD_MINUTES = 15  # 预测未来15分钟的累计收益

# 每年交易日数
TRADING_DAYS_PER_YEAR = 252

# 每天交易小时数（用于分钟数据计算）
# 注意：如果数据是分钟级别，这里应该是每天的交易分钟数
# 日盘4小时 = 240分钟
TRADING_MINUTES_PER_DAY = 240  # 日盘4小时交易（4小时 * 60分钟 = 240分钟）

# 每天小时数（用于小时数据计算）
HOURS_PER_DAY = 4  # 日盘4小时

# 计算年化因子
if DATA_FREQUENCY == 'minute':
    # 分钟数据：直接使用分钟计算
    # 每天有多少个预测周期
    PERIODS_PER_DAY = TRADING_MINUTES_PER_DAY / PREDICTION_PERIOD_MINUTES
else:
    # 小时数据：需要将分钟转换为小时
    PREDICTION_PERIOD_HOURS = PREDICTION_PERIOD_MINUTES / 60
    PERIODS_PER_DAY = HOURS_PER_DAY / PREDICTION_PERIOD_HOURS

PERIODS_PER_YEAR = TRADING_DAYS_PER_YEAR * PERIODS_PER_DAY

